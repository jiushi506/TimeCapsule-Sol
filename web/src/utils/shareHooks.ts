function hashSeed(input: string): number {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function interpolate(template: string, values: Record<string, string>): string {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, value),
    template,
  );
}

export function selectShareHook(
  language: Language,
  mode: CapsuleMode,
  unlockAt: number,
  seed: string,
): SelectedShareHook {
  const nowSeconds = Date.now() / 1000;
  const yearsUntil = Math.max(1, Math.floor(Math.max(0, unlockAt - nowSeconds) / (365.2425 * 24 * 60 * 60)));
  const eligible = HOOK_META
    .map((meta, index) => ({ meta, index }))
    .filter(({ meta }) => meta.modes.includes(mode) && (meta.minYears === undefined || yearsUntil >= meta.minYears));
  const pool = eligible.length ? eligible : HOOK_META.map((meta, index) => ({ meta, index }));
  const choice = pool[hashSeed(seed) % pool.length];
  const localized = HOOK_COPY[language]?.[choice.index] || HOOK_COPY.en[choice.index];
  return {
    id: choice.meta.id,
    category: choice.meta.category,
    text: interpolate(localized, {
      year: String(new Date(unlockAt * 1000).getUTCFullYear()),
      years: String(yearsUntil),
    }),
    yearsUntil,
  };
}

export function buildShareCaption(
  language: Language,
  mode: CapsuleMode,
  hook: string,
): string {
  const ui = POSTER_SHARE_UI[language] || POSTER_SHARE_UI.en;
  const prompt = mode === 'private' ? ui.sharePromptPrivate : ui.sharePromptPublic;
  return `${hook}\n\n${prompt}`;
}

const expectedHookCount = HOOK_META.length;
Object.entries(HOOK_COPY).forEach(([language, hooks]) => {
  if (hooks.length !== expectedHookCount) {
    throw new Error(
      `Share hook translation mismatch for ${language}: expected ${expectedHookCount}, received ${hooks.length}`,
    );
  }
});

